"""The project's models: write the planner and executor here; no simulator or environment code.

What the shared layer calls (types come from observation.py, regenerated by ``run.sh check``):

- ``build_planner()`` / ``build_executor(config, torch_dtype)``: return ``nn.Module``s. The component
  named in scene.yaml ``control.train`` is trained; it receives ``config`` (train.yaml
  ``actor.model``) and ``torch_dtype``. A fixed component's factory takes only the scene.yaml
  ``parameters`` of that component (e.g. a weights file).
- ``forward(obs)``: ``obs`` holds only the observations scene.yaml selects for that component
  (``obs.robot.joint_position`` etc., with batch axis first). A fixed component returns its output
  tensor; the trained one returns (action mean, value [B, 1]) and owns ``actor_logstd``.
- ``decode_action(action, obs)``: turns the executor action into the joint targets of each
  scene.yaml ``control.output`` endpoint, in real units (rad, m, N·m); scaling belongs here.
- ``initial_action(obs)``: the executor output before its first step after a reset (default zeros).

The example below walks a Go2 to ``destination``; replace it when the robot or task changes.
"""
import torch
from torch import Tensor, nn
from shared.policy_math import inverse_rotate, relative_goal, yaw
from .observation import ExecutorObs, ExecutorOutput, ExecutorTargets, PlannerObs, PlannerOutput


class Planner(nn.Module):
    def forward(self, obs: PlannerObs) -> PlannerOutput:
        goal = obs.destination
        return torch.cat((goal.position, yaw(goal.orientation).unsqueeze(-1)), dim=-1)


def build_planner():
    return Planner()


class Executor(nn.Module):
    def __init__(self, config):
        super().__init__()
        def network(output_dim):
            layers = []
            for hidden in config.hidden_dims:
                layers.extend((nn.LazyLinear(hidden), nn.ELU()))
            return nn.Sequential(*layers, nn.LazyLinear(output_dim))
        self.register_buffer("physical_joint_targets_v1", torch.tensor(1))
        self.actor = network(config.action_dim)
        self.actor_logstd = nn.Parameter(torch.full((config.action_dim,), -1.3862943611198906))
        self.value_head = network(1)

    def forward(self, obs: ExecutorObs) -> tuple[ExecutorOutput, Tensor]:
        robot, goal = obs.robot, obs.planner.output
        relative, error = relative_goal(robot.position, robot.orientation, goal[:, :3], goal[:, 3])
        distance = torch.linalg.vector_norm(goal[:, :3] - robot.position, dim=-1, keepdim=True)
        gravity = torch.nn.functional.normalize(obs.simulation.gravity, dim=-1)
        features = torch.cat((inverse_rotate(robot.linear_velocity, robot.orientation),
                              inverse_rotate(robot.angular_velocity, robot.orientation),
                              inverse_rotate(gravity, robot.orientation),
                              robot.joint_position - robot.default_joint_position,
                              robot.joint_velocity - robot.default_joint_velocity,
                              relative, error, distance, (obs.executor.output - robot.default_joint_position) / .25), -1)
        return robot.default_joint_position + .25 * self.actor(features), self.value_head(features)


def build_executor(config, torch_dtype):
    """``config``: train.yaml ``actor.model`` (hidden_dims, action_dim). LazyLinear layers are sized
    from the first real observation before training starts."""
    return Executor(config).to(dtype=torch_dtype)


def decode_action(action: ExecutorOutput, obs: ExecutorObs) -> ExecutorTargets:
    """{endpoint name in scene.yaml control.output: [B, joints] targets}; here the action already is
    the leg joint angles (rad)."""
    return {'legs': action}


def initial_action(obs: ExecutorObs) -> ExecutorOutput:
    return obs.robot.default_joint_position
